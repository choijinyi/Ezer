# === Replacement helpers ===

PLACEHOLDER_PATTERNS = {
    "summary": re.compile(
        r"(## 요약\s*\n+)_\([^)]*5–7줄[^)]*\)_\s*\n+",
        re.DOTALL,
    ),
    "reflect": re.compile(
        r"(## 생각해볼 거리\s*\n+)_\([^)]*\d+개[^)]*\)_\s*\n+(?:\d+\.\s*\n)+",
        re.DOTALL,
    ),
    "further": re.compile(
        r"(## 더 읽을거리\s*\n+)_\([^)]*\d+편[^)]*\)_\s*\n+(?:- ?\s*\n)+",
        re.DOTALL,
    ),
    "recap": re.compile(
        r"(## 우리가 함께 본 것\s*\n+)_\([^)]*1–2쪽[^)]*\)_\s*\n+",
        re.DOTALL,
    ),
    "farewell": re.compile(
        r"(## 독자에게\s*\n+)_\([^)]*1–2쪽[^)]*\)_\s*\n+",
        re.DOTALL,
    ),
}


def replace_summary(text: str, fname: str) -> str:
    if fname not in SUMMARIES:
        return text
    block = SUMMARIES[fname]
    return PLACEHOLDER_PATTERNS["summary"].sub(lambda m: f"{m.group(1)}{block}\n\n", text, count=1)


def replace_reflect(text: str, fname: str) -> str:
    if fname not in REFLECTIONS:
        return text
    items = REFLECTIONS[fname]
    body = "\n".join(f"{i+1}. {q}" for i, q in enumerate(items))
    return PLACEHOLDER_PATTERNS["reflect"].sub(lambda m: f"{m.group(1)}{body}\n\n", text, count=1)


def replace_further(text: str, fname: str) -> str:
    if fname not in FURTHER:
        return text
    items = FURTHER[fname]
    body = "\n".join(f"- {b}" for b in items)
    return PLACEHOLDER_PATTERNS["further"].sub(lambda m: f"{m.group(1)}{body}\n\n", text, count=1)


def replace_closing(text: str) -> str:
    text = PLACEHOLDER_PATTERNS["recap"].sub(lambda m: f"{m.group(1)}{CLOSING_RECAP}\n\n", text, count=1)
    text = PLACEHOLDER_PATTERNS["farewell"].sub(lambda m: f"{m.group(1)}{CLOSING_FAREWELL}\n\n", text, count=1)
    return text


def main():
    body_files = list(SUMMARIES.keys())
    for fname in body_files:
        path = os.path.join(MS_DIR, fname)
        if not os.path.exists(path):
            continue
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
        new = text
        new = replace_summary(new, fname)
        new = replace_reflect(new, fname)
        new = replace_further(new, fname)
        if new != text:
            with open(path, "w", encoding="utf-8") as f:
                f.write(new)
            print(f"  {fname}: 요약/생각/읽을거리 채움")

    # 14장
    path = os.path.join(MS_DIR, "14-forward.md")
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
        new = replace_closing(text)
        if new != text:
            with open(path, "w", encoding="utf-8") as f:
                f.write(new)
            print(f"  14-forward.md: 우리가 함께 본 것 / 독자에게 채움")


if __name__ == "__main__":
    main()
